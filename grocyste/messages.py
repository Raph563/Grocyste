def public_message(error):
    message = str(error)
    if message in MESSAGES:
        return MESSAGES[message]
    # Provisioning and manager errors are curated locally and already French.
    if getattr(error, "code", None) in {"provisioning_failed", "manager_error"}:
        return message
    return "La requête n’a pas pu être traitée. Vérifiez les paramètres et les droits de votre compte."
